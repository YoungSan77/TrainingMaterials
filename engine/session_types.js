// ============================================================================
// session_types.js — 세션 유형별 요건의 단일 소스. 엔진 lint·verify 공유.
//
//   measure.js=폭 / skeleton.js=슬라이드 골격 / shape.js=데이터 형태 /
//   layout.js=기하 에 이은 다섯 번째. 여기는 '세션에 무엇이 있어야 하는가'를 정한다.
//
//   [왜 유형이 필요한가]
//   현상·원인·원칙·적용·타협은 형식이 아니라 '개념을 가르치는 한 가지 교수법'이다.
//   그것이 계약에 박혀 있으니 모든 세션이 그 방식이 됐다 — 워크숍도, 종합 정리도.
//   유형화는 기능 추가가 아니라 그 전제를 밖으로 꺼내 바꿀 수 있게 만드는 일이다.
//
//   [왜 필수를 줄였는가]
//   설명형의 필수가 다섯이면 최소 7장이 강제되고, 거기에 균형을 맞추면 12장이 나온다.
//   실제로 다섯 덱이 전부 12장(계약 범위 12~17의 하한)이었고 셋은 분류 분포까지 같았다.
//   원인이 자명한 주제도 있고 타협이 없는 주제도 있다 → 필수는 현상·원칙·적용 셋.
//
//   [장수는 범위가 아니라 파생값]
//   장수 = 명제 수 + 고정 장. 범위(12~17)를 두면 하한이 목표가 된다.
//   파생값으로 두면 덱에 재량이 없어지고 '이 세션이 얼마나 무거운가'라는 판단이
//   커리큘럼으로 올라간다 — 그게 원래 사람이 할 결정이다.
//
//   [골격은 유형과 무관하다]
//   질문·리드·시각·결론은 워크숍 슬라이드에도 그대로 맞는다. 그래서 렌더 엔진은
//   유형을 모른다 — 유형은 이 표와 두 검사기에만 존재하고 layout/visuals/pages는 손대지 않는다.
//
//   [한계 — 알고 쓴다]
//   분류 어휘 자체는 도메인 중립이 아니다. 현상·원인·원칙도, 준비·진행·산출도 특정
//   교수법의 어휘다. 두 번째 과정이 다른 교수법을 쓰면 이 표를 global_config가
//   주입하게 바꾼다(visualTriggers를 데이터가 주입하게 한 것과 같은 수순). 지금은 아니다.
// ============================================================================

const TYPES = {
    // 개념을 가르치는 세션. 이 과정의 대부분.
    '설명형': {
        fixed: ['학습 목표', '요약'],          // 명제를 갖지 않는 장(회수·예고)
        required: ['현상', '원칙', '적용'],     // 각 최소 1장, statement는 채우지 못한다
        optional: ['원인', '타협'],
        minPerSlide: 4,                        // 분/장 — 분량↔명제 수 정합 검사용
    },
    // 활동을 하는 세션. 논증이 아니므로 어휘가 통째로 다르고, 네댓 장도 정상이다.
    '워크숍형': {
        fixed: ['목표', '디브리프'],
        required: ['준비', '진행', '산출'],
        optional: [],
        minPerSlide: 12,                       // 활동 시간이 대부분이라 장당 시간이 길다
    },
    // 앞의 것들을 엮는 세션. 새 현상·새 원인이 아니라 연결이 내용이다.
    '종합형': {
        fixed: ['요약'],
        required: ['연결'],
        optional: ['적용', '타협'],
        minPerSlide: 4,
    },
};

const DEFAULT = '설명형';                       // 유형 미선언 덱(구 형식)은 설명형으로 본다

const names = () => Object.keys(TYPES);
const spec = (t) => TYPES[t || DEFAULT] || null;

// 이 세션에서 쓸 수 있는 kind 전체
const kinds = (t) => {
    const s = spec(t);
    return s ? [...s.fixed, ...s.required, ...s.optional] : [];
};

// 명제를 갖지 않는 장인가(고정 장)
const isFixed = (t, kind) => {
    const s = spec(t);
    return !!(s && s.fixed.includes(kind));
};

// 명제 수 → 본문 장수. 명제 하나가 한 장이고, 거기에 고정 장이 붙는다.
const slideCount = (t, nClaims) => {
    const s = spec(t);
    return s ? nClaims + s.fixed.length : null;
};

module.exports = { TYPES, DEFAULT, names, spec, kinds, isFixed, slideCount };
